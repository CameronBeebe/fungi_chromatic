"""Compile the fixed grotto's shortest-path direction fields into banked ROM.
No runtime flood fill or terrain bypass: two bits per (destination, origin).
Run after changing the map. The controller rejects blocked/disconnected targets.
"""

import json
from pathlib import Path
from collections import deque

P = Path(__file__).resolve().parents[1]
OUT = P / "plugins/colony-controls/engine/src"
solid = set(map(tuple, json.loads((P / "art/network-layout.json").read_text())["solid"]))
cells = [
    (x, y) for y in range(28) for x in range(31) if (x, y) not in solid and (x + 1, y) not in solid
]
index = {p: i for i, p in enumerate(cells)}
dirs = [(1, 0), (-1, 0), (0, 1), (0, -1)]
stride = (len(cells) + 3) // 4
fields = []
for end in cells:
    paths = {end: 0}
    q = deque([end])
    while q:
        p = q.popleft()
        for d, (dx, dy) in enumerate(dirs):
            t = (p[0] - dx, p[1] - dy)
            if t in index and t not in paths:
                paths[t] = d
                q.append(t)
    # Current map is one connected component; refuse silent invalid routing.
    assert len(paths) == len(cells), "Map has disconnected walkable components"
    field = [0] * stride
    for p, d in paths.items():
        field[index[p] // 4] |= d << (2 * (index[p] % 4))
    fields.append(field)
chunks = [fields[i : i + 128] for i in range(0, len(fields), 128)]
for k, chunk in enumerate(chunks):
    values = ",\n".join(",".join(map(str, row)) for row in chunk)
    (OUT / f"ff_routes_{k}.c").write_text(
        f"""/* Generated by tools/build_navigation.py. */
#pragma bank 255
#include <gbdk/platform.h>
static const UBYTE directions[] = {{{values}}};
UBYTE ff_route_{k}(UWORD start, UBYTE goal) BANKED {{
    return (directions[(UWORD)goal*{stride}+(start>>2)] >> ((start&3)<<1)) & 3;
}}
"""
    )
lookup = [index.get((x, y), 65535) for y in range(28) for x in range(32)]
(OUT / "ff_routes.h").write_text(
    "/* Generated by tools/build_navigation.py. */\n"
    + "\n".join(f"UBYTE ff_route_{k}(UWORD start, UBYTE goal) BANKED;" for k in range(len(chunks)))
    + "\nstatic const UWORD ff_cells[896] = {"
    + ",".join(map(str, lookup))
    + "};\n"
    + "static UBYTE ff_direction(UWORD start, UWORD goal) {\n"
    + "\n".join(
        f"    if (goal < {(k+1)*128}) return ff_route_{k}(start, goal-{k*128});"
        for k in range(len(chunks))
    )
    + "\n    return 0;\n}\n"
)
print(f"{len(cells)} walkable positions; {len(cells)*stride} route bytes; every pair reachable")
