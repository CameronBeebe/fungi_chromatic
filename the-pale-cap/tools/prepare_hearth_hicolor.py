"""Package the reviewed 104px Hi-Color study for GBVM's reserved font tiles.

Run the standalone study build first to regenerate converter outputs. This step
uses its checked-in raw outputs and needs only Python's standard library.
"""
from pathlib import Path
import hashlib
import json

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'art-tests/hearth-hicolor/generated'
ENGINE = ROOT / 'plugins/colony-controls/engine'
tiles = (SOURCE / 'hearth_menu.til').read_bytes()
mapping = (SOURCE / 'hearth_menu.map').read_bytes()
attrs = (SOURCE / 'hearth_menu.atr').read_bytes()
palettes = (SOURCE / 'hearth_menu.pal').read_bytes()
assert len(tiles) == 260 * 16 and len(mapping) == len(attrs) == 260
assert len(palettes) == 105 * 32
assert all(int.from_bytes(palettes[i:i+2], 'little') < 32768
           for i in range(0, len(palettes), 2))
indices = [t + (256 if a & 8 else 0) for t, a in zip(mapping, attrs)]
assert all(i < 260 for i in indices)
new_map = bytes(i if i < 128 else i - 128 for i in indices)
new_attrs = bytes((a & ~8) | (8 if i >= 128 else 0)
                  for i, a in zip(indices, attrs))
# The engine font uses bank 0 C4..FF and bank 1 C0..FF. Neither may overlap.
assert all(t < (192 if a & 8 else 196) for t, a in zip(new_map, new_attrs))
parts = {'tiles': tiles, 'map': new_map, 'attrs': new_attrs, 'colors': palettes}
header = '#ifndef FF_HEARTH_DATA_H\n#define FF_HEARTH_DATA_H\n#include <gbdk/platform.h>\nBANKREF_EXTERN(ff_hearth_data)\n'
source = '// Generated by tools/prepare_hearth_hicolor.py; do not edit.\n#pragma bank 255\n#include "ff_hearth_data.h"\nBANKREF(ff_hearth_data)\n'
for name, data in parts.items():
    symbol = f'ff_hearth_{name}'
    header += f'extern const unsigned char {symbol}[{len(data)}];\n'
    source += f'const unsigned char {symbol}[{len(data)}] = {{\n'
    source += '\n'.join('    ' + ','.join(f'0x{x:02x}' for x in data[i:i+16]) + ','
                        for i in range(0, len(data), 16)) + '\n};\n'
header += '#endif\n'
(ENGINE / 'include/ff_hearth_data.h').write_text(header)
(ENGINE / 'src/ff_hearth_data.c').write_text(source)
print(json.dumps({'payloadBytes': sum(map(len, parts.values())),
                  'tileCount': 260, 'paletteSHA256': hashlib.sha256(palettes).hexdigest()}))
